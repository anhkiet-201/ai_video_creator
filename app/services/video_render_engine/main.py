"""CLI & Example Custom Implementation for Video Render Engine.

Demonstrates:
1. How a user implements `BaseVideoRenderer` using their own preferred tool.
2. How `AntiReupEngine` generates randomized video/audio filter chains and container metadata.
3. How `VideoRenderEngine` runs multiple video renders concurrently across parallel threads.
4. How each thread maintains an isolated in-memory log buffer (no disk I/O for logs).

Run directly:
    python app/services/video_render_engine/main.py
"""

import argparse
import logging
from pathlib import Path
import sys
import time

# Ensure project root is in sys.path
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from app.services.video_render_engine import (
    allocate_next_output_path,
    AntiReupEngine,
    AntiReupProfile,
    BaseVideoRenderer,
    MacOSVideoRenderer,
    WindowsVideoRenderer,
    get_platform_renderer,
    RenderResult,
    ScenePlan,
    TaskLogger,
    VideoRenderConfig,
    VideoRenderEngine,
    VideoRenderPlan,
)

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] [MainProcess] %(message)s",
    datefmt="%H:%M:%S",
)


class ExampleUserRenderer(BaseVideoRenderer):
    """Example implementation of BaseVideoRenderer demonstrating active Anti-Reup usage.

    Users implement their preferred video rendering logic here (e.g. calling FFmpeg CLI,
    GStreamer, hardware encoders, MoviePy, or platform-native SDKs) and apply the
    filter chains generated by AntiReupEngine.
    """

    @property
    def renderer_name(self) -> str:
        return "ExampleUserRenderer"

    def validate_environment(self) -> bool:
        """User checks if their rendering tools are installed and ready."""
        return True

    def render_plan(
        self,
        plan: VideoRenderPlan,
        source_folder: Path,
        config: VideoRenderConfig,
        profile: AntiReupProfile,
        task_logger: TaskLogger,
    ) -> RenderResult:
        """User implements their custom rendering process for a single plan.

        Notice how AntiReupEngine generates the exact filter chains for video, audio, and metadata!
        """
        task_logger.info(f"==> Bắt đầu xử lý {len(plan.scenes)} scenes cho kịch bản: '{plan.title}'")

        # 1. Đọc các thông số ngẫu nhiên từ AntiReupProfile
        task_logger.info("[Anti-Reup] Thông số đã được ngẫu nhiên hóa:")
        for param_key, param_val in profile.params.items():
            task_logger.info(f"   • {param_key}: {param_val}")

        base_dest_dir = config.output_dir or (source_folder.parent / "storage" / "outputs")
        if plan.company_name or not plan.output_filename:
            output_file = allocate_next_output_path(
                base_output_dir=base_dest_dir,
                company_name=plan.company_name,
                sequence_hint=plan.video_index,
            )
            dest_dir = output_file.parent
        else:
            dest_dir = base_dest_dir
            dest_dir.mkdir(parents=True, exist_ok=True)
            output_file = dest_dir / plan.output_filename

        # 2. Xử lý từng phân cảnh theo kịch bản (scenes)
        total_duration = 0.0
        for i, scene in enumerate(plan.scenes):
            task_logger.info(f"   [Scene {i+1}/{len(plan.scenes)}] '{scene.content[:30]}...'")
            total_duration += 2.0  # Giả lập thời lượng mỗi scene
            time.sleep(0.3)

        # 3. Tạo file thành phẩm mô phỏng kèm thông số Anti-Reup
        with open(output_file, "w", encoding="utf-8") as f:
            f.write(f"Rendered video data for {plan.plan_id}\n")
            for param_key, param_val in profile.params.items():
                f.write(f"{param_key}: {param_val}\n")

        file_size = output_file.stat().st_size
        task_logger.info(f"==> Render hoàn tất thành công -> {output_file.name} ({file_size} bytes)")

        return RenderResult(
            plan_id=plan.plan_id,
            output_path=output_file,
            duration=round(total_duration, 2),
            file_size_bytes=file_size,
            metadata=dict(profile.params),
        )


