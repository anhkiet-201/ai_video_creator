def main():
    if hasattr(sys.stdout, "reconfigure"):
        try:
            sys.stdout.reconfigure(encoding="utf-8")
            sys.stderr.reconfigure(encoding="utf-8")
        except Exception:
            pass

    parser = argparse.ArgumentParser(description="Video Render Engine CLI & Multi-Threading Demo")
    parser.add_argument(
        "--source-folder",
        type=str,
        default="assets/samples/company_media",
        help="Thư mục chứa video/ảnh tư liệu",
    )
    parser.add_argument(
        "--max-workers",
        type=int,
        default=3,
        help="Số lượng video render song song đồng thời",
    )
    parser.add_argument(
        "--anti-reup-level",
        type=str,
        choices=["none", "low", "medium", "high"],
        default="medium",
        help="Mức độ thuật toán chống re-up",
    )
    parser.add_argument(
        "--renderer",
        type=str,
        choices=["auto", "windows", "macos", "example"],
        default="auto",
        help="Chọn renderer: 'auto' (tự động theo hệ điều hành), 'windows' (NVIDIA NVENC), 'macos' (VideoToolbox) hoặc 'example' (giả lập)",
    )
    parser.add_argument(
        "--fit-mode",
        type=str,
        choices=["crop", "pad"],
        default="crop",
        help="Cơ chế chuẩn hóa khung hình: 'crop' (lấp đầy) hoặc 'pad' (thêm viền)",
    )
    args = parser.parse_args()

    source_path = PROJECT_ROOT / args.source_folder
    output_path = PROJECT_ROOT / "storage" / "outputs"

    print("=" * 75)
    print("🎬 VIDEO RENDER ENGINE - TÍCH HỢP ANTI-REUP & LOG ĐỘC LẬP ĐA LUỒNG")
    print("=" * 75)
    print(f"📁 Thư mục nguồn         : {source_path}")
    print(f"📁 Thư mục xuất video    : {output_path}")
    print(f"⚡ Số luồng render tối đa : {args.max_workers} worker threads")
    print(f"🛡️ Mức độ Anti-Reup      : {args.anti_reup_level.upper()}")
    print(f"💻 Trình Render          : {args.renderer.upper()}")
    print(f"📐 Fit Mode              : {args.fit_mode.upper()}")
    print("=" * 75)

    # 1. Khởi tạo cấu hình
    config = VideoRenderConfig(
        width=1080,
        height=1920,
        fps=30,
        max_concurrent_tasks=args.max_workers,
        anti_reup_level=args.anti_reup_level,
        output_dir=output_path,
        extra_params={"aspect_mode": args.fit_mode},
    )

    # 2. Khởi tạo renderer tương ứng
    if args.renderer == "auto":
        user_renderer = get_platform_renderer(hardware_accel=True, default_fit_mode=args.fit_mode)
    elif args.renderer == "windows":
        user_renderer = WindowsVideoRenderer(hardware_accel=True, default_fit_mode=args.fit_mode)
    elif args.renderer == "macos":
        user_renderer = MacOSVideoRenderer(hardware_accel=True, default_fit_mode=args.fit_mode)
    else:
        user_renderer = ExampleUserRenderer()

    # 3. Khởi tạo VideoRenderEngine và cấu hình thêm quy tắc random tùy chỉnh
    engine = VideoRenderEngine(
        renderer=user_renderer,
        config=config,
    )
    # Người dùng có thể tự do thêm/ghi đè bất kỳ quy tắc random nào theo ý muốn
    engine.anti_reup_engine.set_rule("rotation_angle", (-0.3, 0.3))      # Góc xoay vi mô
    engine.anti_reup_engine.set_rule("vignette_amount", (0.02, 0.06))     # Độ mờ viền góc

    # 4. Danh sách các video plan cần render
    plans = build_sample_plans()
    # Phân bổ ngẫu nhiên BGM từ assets/sounds/bgm cho mỗi plan với âm lượng 10%
    from app.services.video_render_engine.bgm_manager import allocate_bgm_for_plans
    allocated_bgm = allocate_bgm_for_plans(len(plans))
    for idx, p in enumerate(plans):
        p.bgm_path = allocated_bgm[idx]
        p.bgm_volume = 0.10
    print(f"\n🚀 Khởi chạy render song song {len(plans)} videos (mỗi plan kèm BGM ngẫu nhiên 10%)...")

    start_time = time.time()
    batch_result = engine.render_batch(
        source_folder=source_path,
        plans=plans,
        max_workers=args.max_workers,
        on_progress=lambda res: print(f"   [Progress Update] Đã render xong: {res.plan_id} -> {res.output_path.name}"),
    )
    total_elapsed = time.time() - start_time

    print("\n" + "=" * 75)
    print("📊 BÁO CÁO KẾT QUẢ BATCH RENDER & CÁC THÔNG SỐ RANDOM HÓA (ANTI-REUP)")
    print("=" * 75)
    print(f"Tổng số videos yêu cầu: {batch_result.total_plans}")
    print(f"Thành công            : {batch_result.successful_renders}")
    print(f"Thất bại              : {batch_result.failed_renders}")
    print(f"Tổng thời gian chạy   : {total_elapsed:.2f}s")
    print("\nChi tiết các thông số đã được Randomize độc lập cho từng video:")
    for res in batch_result.results:
        profile = res.anti_reup_profile
        print(f"\n  • Video Plan : {res.plan_id}")
        print(f"    - File ra  : {res.output_path}")
        print(f"    - Thời gian: {res.render_time_seconds}s (Thời lượng: {res.duration}s)")
        if profile:
            print("    - 🎲 Danh sách thông số đã random (profile.params):")
            for k, v in profile.params.items():
                print(f"       + {k:20s}: {v}")
        print(f"    - 📜 Số dòng log in-memory: {len(res.logs)}")
    print("=" * 75)


if __name__ == "__main__":
    main()
